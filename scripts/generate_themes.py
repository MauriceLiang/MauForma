#!/usr/bin/env python3
"""Rebuild assets/themes.css from assets/theme-presets.json (stdlib only)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "theme-presets.json"
TARGET = ROOT / "assets" / "themes.css"


def css_block(selector, properties):
    lines = [f"{selector} {{"]
    lines += [f"  --spui-{key}: {value};" for key, value in properties.items()]
    lines.append("}")
    return "\n".join(lines)


def render(data):
    defaults = data["defaults"]
    out = ["/* AUTO-GENERATED by scripts/generate_themes.py. Edit theme-presets.json, not this file. */",
           "/* Theme colors are creative editable examples, not copied from the source website. */",
           css_block(".spui", defaults["light"]),
           ".spui { color-scheme: light; }",
           css_block('.spui[data-scheme="dark"]', defaults["dark"]),
           '.spui[data-scheme="dark"] { color-scheme: dark; }']
    for slug, theme in data["themes"].items():
        out.append(f"\n/* {theme['label']}: {theme['intent']} */")
        out.append(css_block(f'.spui[data-theme="{slug}"]', theme["light"]))
        out.append(css_block(f'.spui[data-theme="{slug}"][data-scheme="dark"]', (defaults["dark"] | theme["dark"])))
    return "\n\n".join(out) + "\n"


if __name__ == "__main__":
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    TARGET.write_text(render(data), encoding="utf-8")
    print(f"Generated {TARGET.relative_to(ROOT)} from {SOURCE.relative_to(ROOT)}")
